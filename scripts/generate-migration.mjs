// Generates db/migration-v1.0-real-data.sql from the raw source SQL file.
// The source file has incompatible schema (TEXT agendas, wrong column names).
// This script extracts raw VALUES and wraps them in safe INSERT statements.

import { readFileSync, writeFileSync } from 'fs'
import { join, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const srcFile = join(__dirname, '../data/infracoop_bd_v4 (1).sql')
const outFile = join(__dirname, '../db/migration-v1.0-real-data.sql')

const src = readFileSync(srcFile, 'utf8')
const lines = src.split('\n')

// Extract raw VALUES lines for a given id prefix (DS- or NM-).
// Handles multi-line strings by joining continuation lines.
function extractRows(prefix) {
  const rows = []
  let current = null

  for (const line of lines) {
    if (line.trimStart().startsWith(`('${prefix}`)) {
      if (current !== null) rows.push(current)
      current = line.trimEnd()
    } else if (current !== null) {
      // continuation line (multi-line string inside a tuple)
      const joined = current + ' ' + line.trim()
      // If this line ends the tuple (has trailing , or ;) stop accumulating
      current = joined
    }
    // detect end of this row: balanced parens
    if (current !== null) {
      const clean = current.replace(/'[^']*'/g, '')
      const opens = (clean.match(/\(/g) || []).length
      const closes = (clean.match(/\)/g) || []).length
      if (closes >= opens) {
        rows.push(current)
        current = null
      }
    }
  }
  if (current !== null) rows.push(current)

  return rows.map(r => r.trimEnd().replace(/,\s*$/, '').replace(/;\s*$/, '').trim())
}

const dsRows = extractRows('DS-')
const nmRows = extractRows('NM-')

console.log(`Found ${dsRows.length} datasets, ${nmRows.length} normativas`)

const out = []

out.push(`-- ================================================================`)
out.push(`--  Migration v1.0 — Real data import (86 datasets + ${nmRows.length} normativas)`)
out.push(`--  Generated by scripts/generate-migration.mjs`)
out.push(`--  Safe to re-run: uses ON CONFLICT (id) DO UPDATE`)
out.push(`-- ================================================================`)
out.push(``)

// ── DATASETS ────────────────────────────────────────────────────────────────
// Source columns (positional): id, titulo, fuente_organismo, pais_iso3,
//   anio_publicacion, subtema, agendas(TEXT), frecuencia, desagregacion_geog,
//   accesibilidad_formato, url_descarga, descripcion_notas
out.push(`-- Step 1: load raw datasets into staging table`)
out.push(`CREATE TEMP TABLE _staging_datasets (`)
out.push(`  id                    TEXT,`)
out.push(`  titulo                TEXT,`)
out.push(`  fuente_organismo      TEXT,`)
out.push(`  pais_iso3             TEXT,`)
out.push(`  anio_publicacion      INTEGER,`)
out.push(`  subtema               TEXT,`)
out.push(`  agendas_raw           TEXT,`)
out.push(`  frecuencia            TEXT,`)
out.push(`  desagregacion_geog    TEXT,`)
out.push(`  accesibilidad_formato TEXT,`)
out.push(`  url_descarga          TEXT,`)
out.push(`  descripcion_notas     TEXT`)
out.push(`);`)
out.push(``)
out.push(`INSERT INTO _staging_datasets VALUES`)
out.push(dsRows.join(',\n') + ';')
out.push(``)

out.push(`-- Step 2: migrate staging → datasets with schema transformation`)
out.push(`INSERT INTO datasets (`)
out.push(`  id, titulo, fuente_organismo, pais_iso3, anio_publicacion,`)
out.push(`  subtema, agendas, frecuencia, desagregacion_geo,`)
out.push(`  accesibilidad_formato, url_descarga, descripcion_notas,`)
out.push(`  es_sintetico, url_valida`)
out.push(`)`)
out.push(`SELECT`)
out.push(`  id, titulo, fuente_organismo, pais_iso3, anio_publicacion,`)
out.push(`  subtema,`)
out.push(`  -- convert 'Ag. Género · Ag. Datos' → ARRAY['Ag. Género','Ag. Datos']`)
out.push(`  ARRAY(SELECT trim(x) FROM unnest(string_to_array(agendas_raw, '·')) AS x),`)
out.push(`  frecuencia,`)
out.push(`  desagregacion_geog,  -- column rename`)
out.push(`  accesibilidad_formato, url_descarga, descripcion_notas,`)
out.push(`  false,  -- es_sintetico`)
out.push(`  true    -- url_valida`)
out.push(`FROM _staging_datasets`)
out.push(`ON CONFLICT (id) DO UPDATE SET`)
out.push(`  titulo                = EXCLUDED.titulo,`)
out.push(`  fuente_organismo      = EXCLUDED.fuente_organismo,`)
out.push(`  pais_iso3             = EXCLUDED.pais_iso3,`)
out.push(`  anio_publicacion      = EXCLUDED.anio_publicacion,`)
out.push(`  subtema               = EXCLUDED.subtema,`)
out.push(`  agendas               = EXCLUDED.agendas,`)
out.push(`  frecuencia            = EXCLUDED.frecuencia,`)
out.push(`  desagregacion_geo     = EXCLUDED.desagregacion_geo,`)
out.push(`  accesibilidad_formato = EXCLUDED.accesibilidad_formato,`)
out.push(`  url_descarga          = EXCLUDED.url_descarga,`)
out.push(`  descripcion_notas     = EXCLUDED.descripcion_notas,`)
out.push(`  es_sintetico          = false;`)
out.push(``)
out.push(`DROP TABLE _staging_datasets;`)
out.push(``)

// ── NORMATIVAS ───────────────────────────────────────────────────────────────
// Source columns: id, nombre, organismo_emisor, tipo, pais_alcance,
//   anio_adopcion, articulo(TEXT), obligacion_datos, agendas(TEXT),
//   url_texto_oficial, descripcion_notas
out.push(`-- Step 3: load raw normativas into staging table`)
out.push(`CREATE TEMP TABLE _staging_normativas (`)
out.push(`  id                TEXT,`)
out.push(`  nombre            TEXT,`)
out.push(`  organismo_emisor  TEXT,`)
out.push(`  tipo              TEXT,`)
out.push(`  pais_alcance      TEXT,`)
out.push(`  anio_adopcion     INTEGER,`)
out.push(`  articulo          TEXT,`)
out.push(`  obligacion_datos  TEXT,`)
out.push(`  agendas_raw       TEXT,`)
out.push(`  url_texto_oficial TEXT,`)
out.push(`  descripcion_notas TEXT`)
out.push(`);`)
out.push(``)
out.push(`INSERT INTO _staging_normativas VALUES`)
out.push(nmRows.join(',\n') + ';')
out.push(``)

out.push(`-- Step 4: migrate staging → normativas with schema transformation`)
out.push(`INSERT INTO normativas (`)
out.push(`  id, nombre, organismo_emisor, tipo, pais_alcance, anio_adopcion,`)
out.push(`  articulo_numeral, obligacion_datos, agendas,`)
out.push(`  url_texto_oficial, descripcion_notas, es_sintetico`)
out.push(`)`)
out.push(`SELECT`)
out.push(`  id, nombre, organismo_emisor, tipo, pais_alcance, anio_adopcion,`)
out.push(`  articulo,  -- column rename → articulo_numeral`)
out.push(`  obligacion_datos,`)
out.push(`  ARRAY(SELECT trim(x) FROM unnest(string_to_array(agendas_raw, '·')) AS x),`)
out.push(`  url_texto_oficial, descripcion_notas,`)
out.push(`  false  -- es_sintetico`)
out.push(`FROM _staging_normativas`)
out.push(`ON CONFLICT (id) DO UPDATE SET`)
out.push(`  nombre            = EXCLUDED.nombre,`)
out.push(`  organismo_emisor  = EXCLUDED.organismo_emisor,`)
out.push(`  tipo              = EXCLUDED.tipo,`)
out.push(`  pais_alcance      = EXCLUDED.pais_alcance,`)
out.push(`  anio_adopcion     = EXCLUDED.anio_adopcion,`)
out.push(`  articulo_numeral  = EXCLUDED.articulo_numeral,`)
out.push(`  obligacion_datos  = EXCLUDED.obligacion_datos,`)
out.push(`  agendas           = EXCLUDED.agendas,`)
out.push(`  url_texto_oficial = EXCLUDED.url_texto_oficial,`)
out.push(`  descripcion_notas = EXCLUDED.descripcion_notas,`)
out.push(`  es_sintetico      = false;`)
out.push(``)
out.push(`DROP TABLE _staging_normativas;`)
out.push(``)
out.push(`-- Done. Verify with:`)
out.push(`-- SELECT COUNT(*) FROM datasets WHERE es_sintetico = false;`)
out.push(`-- SELECT COUNT(*) FROM normativas WHERE es_sintetico = false;`)

writeFileSync(outFile, out.join('\n'), 'utf8')
console.log(`Written to ${outFile}`)
